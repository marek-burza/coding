"""
You have a sequence of events generated by users, ordered in time.
Count the number of users who generated more than `limit` of events
over the last `window` of minutes.
Time constraint on event processing is `O(1)` amortized time complexity.
"""

from collections import Counter, deque


class EventStatistics:
    def __init__(self, window: int, limit: int) -> None:
        self._counters: Counter[int] = Counter()
        self._count_above_limit = 0
        self._window = window
        self._limit = limit
        self._queue: deque[tuple[int, int]] = deque()

    def _clean(self, now: int) -> None:
        while self._queue:
            then, user = self._queue[0]
            if now - then < self._window:
                break
            self._queue.popleft()
            self._counters[user] -= 1
            if self._counters[user] == self._limit - 1:
                self._count_above_limit -= 1
            if self._counters[user] == 0:
                del self._counters[user]

    def event(self, now: int, user: int) -> None:
        self._queue.append((now, user))
        self._counters[user] += 1
        if self._counters[user] == self._limit:
            self._count_above_limit += 1
        self._clean(now)

    def get_count_above_limit(self, now: int) -> int:
        self._clean(now)
        return self._count_above_limit


class TestCode:
    def test_boundary_handling(self) -> None:
        stats = EventStatistics(window=5, limit=1)
        stats.event(0, 1)
        stats.event(1, 2)
        assert stats.get_count_above_limit(4) == 2
        assert stats.get_count_above_limit(5) == 1
        assert stats.get_count_above_limit(6) == 0

    def test_counter_decay(self) -> None:
        stats = EventStatistics(window=10, limit=3)
        for t in (0, 1, 2):
            stats.event(t, 1)
        assert stats.get_count_above_limit(2) == 1
        assert stats.get_count_above_limit(9) == 1
        assert stats.get_count_above_limit(10) == 0
        assert stats.get_count_above_limit(12) == 0

    def test_two_users_sequenced(self) -> None:
        stats = EventStatistics(window=10, limit=2)
        stats.event(0, 1)
        stats.event(1, 1)
        assert stats.get_count_above_limit(9) == 1
        stats.event(9, 2)
        stats.event(10, 2)
        assert stats.get_count_above_limit(10) == 1
        assert stats.get_count_above_limit(11) == 1
        assert stats.get_count_above_limit(19) == 0

    def test_three_users_interleaved(self) -> None:
        stats = EventStatistics(window=10, limit=2)
        for uid in (1, 2, 3):
            stats.event(0, uid)
        for uid in (1, 2, 3):
            stats.event(1, uid)
        assert stats.get_count_above_limit(2) == 3
        assert stats.get_count_above_limit(10) == 0
        assert stats.get_count_above_limit(11) == 0

    def test_single_timestamp(self) -> None:
        stats = EventStatistics(window=5, limit=3)
        for _ in range(5):
            stats.event(7, 1)
        for _ in range(2):
            stats.event(7, 2)
        assert stats.get_count_above_limit(7) == 1
        assert stats.get_count_above_limit(11) == 1
        assert stats.get_count_above_limit(12) == 0
